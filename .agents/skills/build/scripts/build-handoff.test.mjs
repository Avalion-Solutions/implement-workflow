import { approve, authorizeRoutine, checkApproval, checkBudget, checkTimeBudget, closeStage, compactReceipt, initialize, reconcile, recordManifest, renderReport, telemetryTeam, validateAuthorizationManifest, validateManifest } from "./build-handoff.mjs";

function manifest(overrides = {}) {
  return {
    schemaVersion: 1,
    kind: "plan",
    runId: "run-one",
    stage: "brainstorm",
    status: "completed",
    source: { repo: "fixture", base: "abc", commit: "def" },
    objective: "Produce an approved plan",
    decisions: [], criteria: [], inputs: [], outputs: [], checks: [], findings: [], blockers: [], artifacts: [], next: [],
    ...overrides,
  };
}

function authorizations(overrides = {}) {
  return {
    schemaVersion: 1,
    kind: "authorization",
    runId: "run-one",
    status: "ready",
    reviewedCategories: ["filesystem", "git", "dependencies", "external-systems", "identity-access", "cost-lifecycle", "recovery"],
    operations: [{ id: "AUTH-001", category: "filesystem", action: "replace generated package files", targets: ["plugins/basics"], consequence: "generated content is replaced from canonical source", bounds: "only files generated by the plugin sync" }],
    excluded: [{ id: "AUTH-X01", action: "merge protected branch", reason: "separate approval required" }],
    unresolved: [],
    evidence: ["inspected repository status and generator inputs"],
    ...overrides,
  };
}

function unattendedAuthorizations(overrides = {}) {
  return authorizations({
    execution: {
      mode: "bounded-unattended",
      maxAttemptsPerOperation: 2,
      stopConditions: [
        { id: "STOP-001", condition: "An operation would exceed its approved targets or cost bounds", reason: "New user authority is required" },
        { id: "STOP-002", condition: "A protected-branch merge is the next action", reason: "Merge approval is always separate" },
      ],
    },
    operations: [
      { id: "AUTH-001", category: "external-systems", action: "create the named review resource", targets: ["projects/example/review"], consequence: "creates one bounded review resource", bounds: "one resource and no more than USD 10 monthly" },
      { id: "AUTH-REC-001", category: "recovery", trigger: "AUTH-001 reports that the default edition is incompatible with the approved tier", action: "retry creation with --edition=ENTERPRISE", targets: ["projects/example/review"], consequence: "creates the same resource with an explicit compatible edition", bounds: "same version, tier, region, storage, IAM, and cost ceiling", dependsOn: ["AUTH-001"], maxAttempts: 1 },
      { id: "AUTH-DER-001", category: "external-systems", action: "import --approval approve:${resolved.sha256}", targets: ["projects/example/review/database", "resolved-manifest.json"], consequence: "imports only the verified materialized rows", bounds: "source hash and row count must match the approved fixture", dependsOn: ["AUTH-001"], derivation: { inputs: ["resolved-manifest.json"], procedure: "Compute SHA-256 over the exact materialized bytes", validation: "Verify the approved source hash, row count, checksums, and immutable generations before substitution" } },
    ],
    ...overrides,
  });
}

function routineAuthorizations(overrides = {}) {
  return unattendedAuthorizations({
    operations: [{
      id: "AUTH-001",
      authority: "task",
      category: "filesystem",
      action: "edit the requested repository files",
      targets: ["src/requested-feature"],
      consequence: "updates only the user-requested implementation",
      bounds: "the stated task scope and existing repository checks",
    }],
    ...overrides,
  });
}

test("manifest validation enforces the common envelope", () => {
  assert.deepEqual(validateManifest(manifest()), { ok: true, kind: "plan", runId: "run-one", stage: "brainstorm", status: "completed" });
  assert.throws(() => validateManifest({ ...manifest(), blockers: undefined }), /blockers must be an array/);
  assert.throws(() => validateManifest({ ...manifest(), status: "ready" }), /Invalid manifest status/);
  assert.throws(() => validateManifest({ ...manifest(), stage: "red" }), /Invalid manifest stage/);
  assert.throws(() => validateManifest({ ...manifest(), kind: "candidate" }), /cannot use stage brainstorm/);
  assert.throws(() => validateManifest({ ...manifest(), kind: "seed", stage: "seed-tests", checks: [{ command: "node test.mjs", result: "expected-failure", exitCode: 0, commit: "def", evidence: "unexpected pass" }] }), /nonzero exitCode/);
  assert.throws(() => validateManifest({ ...manifest(), kind: "candidate", stage: "blue", checks: [{ command: "node test.mjs", result: "passed", exitCode: 0, commit: "stale", evidence: "suite passed" }] }), /does not match source.commit/);
  assert.throws(() => validateManifest({ ...manifest(), kind: "review", stage: "red-1", findings: [{ id: "RT-x-1", scopeDisposition: "in-scope", repairDisposition: "maybe" }] }), /repairDisposition/);
  assert.throws(() => validateManifest({ ...manifest(), kind: "review", stage: "red-1", findings: [{ id: "RT-x-1", repairDisposition: "eligible", scopeDisposition: "out-of-scope", criterionIds: ["C1"] }] }), /must be in-scope/);
  assert.throws(() => validateManifest({ ...manifest(), kind: "review", stage: "red-1", findings: [{ id: "RT-x-1", repairDisposition: "deferred", scopeDisposition: "out-of-scope" }] }), /deferReason/);
  assert.throws(() => validateManifest({ ...manifest(), kind: "repair", stage: "fixer-1", findings: [{ id: "RT-x-1", result: "maybe" }] }), /result/);
});

test("authorization validation requires complete bounded preflight", () => {
  assert.deepEqual(validateAuthorizationManifest(authorizations()), { ok: true, runId: "run-one", operations: 1, excluded: 1 });
  assert.throws(() => validateAuthorizationManifest(authorizations({ reviewedCategories: ["filesystem"] })), /category was not reviewed/);
  assert.throws(() => validateAuthorizationManifest(authorizations({ unresolved: ["cloud identity"] })), /unresolved items/);
  assert.throws(() => validateAuthorizationManifest(authorizations({ operations: [{ ...authorizations().operations[0], targets: [] }] })), /exact targets/);
});

test("bounded unattended authorization validates recovery and deterministic derivation envelopes", () => {
  assert.deepEqual(validateAuthorizationManifest(unattendedAuthorizations()), {
    ok: true,
    runId: "run-one",
    operations: 3,
    excluded: 1,
    executionMode: "bounded-unattended",
  });
  assert.throws(() => validateAuthorizationManifest(unattendedAuthorizations({ execution: { mode: "bounded-unattended", maxAttemptsPerOperation: 0, stopConditions: [] } })), /maxAttemptsPerOperation/);
  assert.throws(() => validateAuthorizationManifest(unattendedAuthorizations({ execution: { mode: "unknown", maxAttemptsPerOperation: 2, stopConditions: [] } })), /execution mode/);
  assert.throws(() => validateAuthorizationManifest(unattendedAuthorizations({ operations: [{ ...unattendedAuthorizations().operations[1], dependsOn: ["AUTH-MISSING"] }] })), /unknown operation/);
  assert.throws(() => validateAuthorizationManifest(unattendedAuthorizations({ operations: [{ ...unattendedAuthorizations().operations[2], derivation: { inputs: [], procedure: "hash", validation: "check" } }] })), /derivation.inputs/);
});

test("routine task authorization binds a concrete request without a second confirmation", () => {
  const root = mkdtempSync(join(tmpdir(), "build-routine-authorization-"));
  const statusDir = join(root, "status");
  const planPath = join(statusDir, "handoffs", "plan.json");
  const scopePath = join(root, "scope.txt");
  const authorizationPath = join(statusDir, "handoffs", "authorizations.json");
  try {
    initialize({ "status-dir": statusDir, run: "run-one", repo: "fixture", base: "abc", branch: "build/run-one", environment: {} });
    writeFileSync(planPath, `${JSON.stringify(manifest(), null, 2)}\n`);
    writeFileSync(scopePath, "criterion-1\n");
    writeFileSync(authorizationPath, `${JSON.stringify(routineAuthorizations(), null, 2)}\n`);
    recordManifest({ "status-dir": statusDir, file: planPath });

    const bound = authorizeRoutine({ "status-dir": statusDir, plan: planPath, scope: scopePath, authorizations: authorizationPath, event: "task-request" });
    assert.equal(bound.authorizationType, "task");
    assert.deepEqual(checkApproval({ "status-dir": statusDir, plan: planPath, scope: scopePath, authorizations: authorizationPath, operations: "AUTH-001" }).operations, ["AUTH-001"]);
    assert.throws(() => authorizeRoutine({ "status-dir": statusDir, plan: planPath, scope: scopePath, authorizations: authorizationPath, event: "task-request" }), /already bound/);

    writeFileSync(authorizationPath, `${JSON.stringify(unattendedAuthorizations(), null, 2)}\n`);
    assert.throws(() => authorizeRoutine({ "status-dir": statusDir, plan: planPath, scope: scopePath, authorizations: authorizationPath, event: "task-request" }), /explicit approval/);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("existing runs reuse their recorded worktree after the configured root changes", () => {
  const root = mkdtempSync(join(tmpdir(), "build-existing-worktree-"));
  const statusDir = join(root, "status");
  const legacyRoot = join(root, "legacy-root");
  const configuredRoot = join(root, "configured-root");
  mkdirSync(legacyRoot);
  mkdirSync(configuredRoot);
  const options = { "status-dir": statusDir, run: "run-one", repo: "fixture", base: "abc", branch: "build/run-one" };
  try {
    initialize({ ...options, environment: { BASICS_TEMP_ROOT: legacyRoot } });
    const reused = initialize({ ...options, environment: { BASICS_TEMP_ROOT: configuredRoot } });
    const ledger = JSON.parse(readFileSync(join(statusDir, "handoffs", "run-ledger.json"), "utf8"));

    assert.equal(reused.reused, true);
    assert.equal(ledger.worktree.root, legacyRoot);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("compact receipts omit detailed evidence and cap artifact references", () => {
  const value = manifest({
    checks: [{ result: "passed", evidence: "large raw output" }, { result: "passed" }],
    artifacts: Array.from({ length: 12 }, (_, index) => ({ path: `/tmp/artifact-${index}`, contents: "not copied" })),
  });
  const receipt = compactReceipt(value, "/tmp/plan.json", "2026-08-10T00:00:00.000Z");
  assert.deepEqual(receipt.checks, { passed: 2 });
  assert.equal(receipt.artifacts.length, 8);
  assert.doesNotMatch(JSON.stringify(receipt), /large raw output|not copied/);
});

test("close-stage promotes, records, and idempotently reconciles terminal telemetry", () => {
  const root = mkdtempSync(join(tmpdir(), "build-close-stage-"));
  const statusDir = join(root, "status");
  try {
    initialize({ "status-dir": statusDir, run: "run-one", repo: "fixture", base: "abc", branch: "build/run-one", environment: {} });
    const statusScript = join(import.meta.dirname, "build-status.mjs");
    const initialized = spawnSync(process.execPath, [statusScript, "init", "--state-dir", statusDir, "--run", "run-one", "--repo", "fixture", "--base", "abc", "--branch", "build/run-one"], { encoding: "utf8" });
    assert.equal(initialized.status, 0, initialized.stderr);
    const staged = join(root, "staged-plan.json");
    writeFileSync(staged, `${JSON.stringify(manifest(), null, 2)}\n`);
    assert.equal(closeStage({ "status-dir": statusDir, file: staged }).pending, 0);
    const canonical = join(statusDir, "handoffs", "plan.json");
    const ledger = JSON.parse(readFileSync(join(statusDir, "handoffs", "run-ledger.json"), "utf8"));
    const status = JSON.parse(readFileSync(join(statusDir, "status.json"), "utf8"));
    assert.equal(ledger.stages.brainstorm.manifest, canonical);
    assert.equal(ledger.stages.brainstorm.telemetry.state, "synchronized");
    assert.equal(status.teams.brainstorm.status, "completed");
    assert.equal(status.teams.brainstorm.progress, 100);
    const count = readFileSync(join(statusDir, "events.ndjson"), "utf8").split("\n").filter((line) => line.includes(ledger.stages.brainstorm.telemetry.id)).length;
    closeStage({ "status-dir": statusDir, file: staged });
    reconcile({ "status-dir": statusDir });
    const repeated = readFileSync(join(statusDir, "events.ndjson"), "utf8").split("\n").filter((line) => line.includes(ledger.stages.brainstorm.telemetry.id)).length;
    assert.equal(count, 1);
    assert.equal(repeated, 1);
    assert.equal(telemetryTeam("red-2"), "red");
    assert.equal(telemetryTeam("fixer-3"), "fixer");
    assert.throws(() => closeStage({ "status-dir": statusDir, file: staged.replace("staged-plan", "missing") }), /ENOENT/);
    writeFileSync(staged, `${JSON.stringify(manifest({ status: "blocked" }), null, 2)}\n`);
    assert.throws(() => closeStage({ "status-dir": statusDir, file: staged }), /requires completed or not-required/);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("ledger enforces one scoped Red/Fixer round, approval, budgets, and readiness", () => {
  const root = mkdtempSync(join(tmpdir(), "build-handoff-"));
  const statusDir = join(root, "status");
  const planPath = join(statusDir, "handoffs", "plan.json");
  const scopePath = join(root, "scope.txt");
  const authorizationPath = join(statusDir, "handoffs", "authorizations.json");
  const reportPath = join(root, "report.md");
  try {
    initialize({ "status-dir": statusDir, run: "run-one", repo: "fixture", base: "abc", branch: "build/run-one", environment: {} });
    assert.throws(() => initialize({ "status-dir": statusDir, run: "run-one", repo: "other", base: "abc", branch: "build/run-one", environment: {} }), /repo does not match/);
    writeFileSync(planPath, `${JSON.stringify(manifest(), null, 2)}\n`);
    writeFileSync(scopePath, "criterion-1\n");
    writeFileSync(authorizationPath, `${JSON.stringify(unattendedAuthorizations(), null, 2)}\n`);
    const recordStage = (name, kind, status, extra = {}) => {
      const path = join(statusDir, "handoffs", `${name}.json`);
      writeFileSync(path, `${JSON.stringify(manifest({ kind, stage: name, status, ...extra }), null, 2)}\n`);
      return recordManifest({ "status-dir": statusDir, file: path });
    };
    let result = recordManifest({ "status-dir": statusDir, file: planPath });
    assert.equal(result.stage, "brainstorm");
    const approved = approve({ "status-dir": statusDir, plan: planPath, scope: scopePath, authorizations: authorizationPath, event: "approval-1" });
    assert.equal(approved.executionMode, "bounded-unattended");
    assert.deepEqual(checkApproval({ "status-dir": statusDir, plan: planPath, scope: scopePath, authorizations: authorizationPath, operations: "AUTH-001,AUTH-REC-001" }).operations, ["AUTH-001", "AUTH-REC-001"]);
    assert.throws(() => checkApproval({ "status-dir": statusDir, plan: planPath, scope: scopePath, authorizations: authorizationPath, operations: "AUTH-MISSING" }), /not approved/);

    recordStage("seed-tests", "seed", "completed", {
      source: { repo: "fixture", base: "abc", commit: "seed" },
      checks: [{ command: "node test.mjs", result: "expected-failure", exitCode: 1, commit: "seed", evidence: "assertion failed as seeded" }],
    });
    recordStage("blue", "candidate", "completed", {
      source: { repo: "fixture", base: "abc", commit: "blue" },
      checks: [{ command: "node test.mjs", result: "passed", exitCode: 0, commit: "blue", evidence: "suite passed" }],
      inputs: [{ kind: "seed", commit: "seed" }],
    });
    recordStage("red-1", "review", "completed", { source: { repo: "fixture", base: "abc", commit: "blue" } });
    recordStage("fixer-1", "repair", "not-required", { source: { repo: "fixture", base: "abc", commit: "blue" } });
    recordStage("integration", "integration", "completed", {
      source: { repo: "fixture", base: "abc", commit: "integrated" },
      checks: [{ command: "node test.mjs", result: "passed", exitCode: 0, commit: "integrated", evidence: "suite passed" }],
      inputs: [{ kind: "reviewed-candidate", commit: "blue" }],
    });
    result = renderReport({ "status-dir": statusDir, output: reportPath });
    assert.equal(result.ready, true);
    assert.match(readFileSync(reportPath, "utf8"), /Ready for explicit merge approval/);

    const deferred = { id: "RT-edge-1", scopeDisposition: "out-of-scope", repairDisposition: "deferred", deferReason: "Not required by the approved plan" };
    recordStage("red-1", "review", "completed", { source: { repo: "fixture", base: "abc", commit: "blue" }, findings: [deferred] });
    assert.equal(renderReport({ "status-dir": statusDir, output: reportPath }).ready, true, "deferred findings remain report-only");
    assert.match(readFileSync(reportPath, "utf8"), /1 report-only finding/);

    const eligible = { id: "RT-logic-1", scopeDisposition: "in-scope", repairDisposition: "eligible", criterionIds: ["C1"] };
    recordStage("red-1", "review", "completed", { source: { repo: "fixture", base: "abc", commit: "blue" }, findings: [eligible, deferred] });
    assert.equal(renderReport({ "status-dir": statusDir, output: reportPath }).ready, false, "an in-scope eligible finding requires Fixer");
    recordStage("fixer-1", "repair", "completed", {
      source: { repo: "fixture", base: "abc", commit: "fixed" },
      inputs: [{ kind: "review", commit: "blue" }],
      findings: [{ id: "RT-logic-1", result: "fixed" }],
      checks: [{ command: "node fixed.mjs", result: "passed", exitCode: 0, commit: "fixed", evidence: "scoped judge passed" }],
    });
    recordStage("integration", "integration", "completed", {
      source: { repo: "fixture", base: "abc", commit: "integrated-fixed" },
      checks: [{ command: "node test.mjs", result: "passed", exitCode: 0, commit: "integrated-fixed", evidence: "suite passed" }],
      inputs: [{ kind: "reviewed-candidate", commit: "fixed" }],
    });
    assert.equal(renderReport({ "status-dir": statusDir, output: reportPath }).ready, true, "one scoped Fixer/Judge round can satisfy readiness");

    recordStage("red-2", "review", "completed", { source: { repo: "fixture", base: "abc", commit: "fixed" } });
    assert.equal(renderReport({ "status-dir": statusDir, output: reportPath }).ready, false, "repeated Red rounds are outside fast Build readiness");

    writeFileSync(scopePath, "criterion-2\n");
    assert.throws(() => checkApproval({ "status-dir": statusDir, plan: planPath, scope: scopePath, authorizations: authorizationPath }), /scope changed/);

    writeFileSync(scopePath, "criterion-1\n");
    writeFileSync(authorizationPath, `${JSON.stringify(unattendedAuthorizations({ evidence: ["changed preview"] }), null, 2)}\n`);
    assert.throws(() => checkApproval({ "status-dir": statusDir, plan: planPath, scope: scopePath, authorizations: authorizationPath }), /authorizations changed/);

    const largeOutput = join(root, "output.log");
    writeFileSync(largeOutput, `${"x".repeat(2200)}\n`);
    result = checkBudget({ "status-dir": statusDir, kind: "output", file: largeOutput });
    assert.equal(result.warning, true);

    const ledgerBeforeTime = JSON.parse(readFileSync(join(statusDir, "handoffs", "run-ledger.json"), "utf8"));
    const started = Date.parse(ledgerBeforeTime.createdAt);
    assert.equal(checkTimeBudget({ "status-dir": statusDir }, started + 31 * 60000).state, "target-exceeded");
    assert.equal(checkTimeBudget({ "status-dir": statusDir }, started + 46 * 60000).state, "hard-stop");

    result = renderReport({ "status-dir": statusDir, output: reportPath });
    assert.equal(result.ready, false);
    assert.match(readFileSync(reportPath, "utf8"), /Not ready for merge approval/);
    const ledger = JSON.parse(readFileSync(join(statusDir, "handoffs", "run-ledger.json"), "utf8"));
    assert.equal(ledger.worktree.runRoot.endsWith("/build-runs/run-one"), true);
    assert.equal(ledger.worktree.integration.endsWith("/build-runs/run-one/integration"), true);
    assert.equal(ledger.stages.brainstorm.manifest, planPath);
    assert.equal(ledger.proxyWarnings.length, 1);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});
